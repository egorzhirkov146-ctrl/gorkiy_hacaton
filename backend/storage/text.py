"""Нормализация русского текста для полнотекстового поиска.

FTS5 в SQLite не умеет склонять русские слова, поэтому поиск отрезает
окончание у слова запроса и ищет основу как префикс ("договору" -> "договор*").
"""
from __future__ import annotations

import re

_WORD_RE = re.compile(r"\w+", re.UNICODE)

# Окончания отсортированы по убыванию длины, чтобы сначала срезать самое длинное.
_ENDINGS = sorted(
    {
        "иями", "ями", "ами", "иях", "ях", "ах", "ием", "ией", "ей", "ой", "ий", "ый",
        "ая", "яя", "ое", "ее", "ые", "ие", "ую", "юю", "ом", "ем", "ам", "ям", "ов",
        "ев", "ью", "ия", "ие", "ии", "иться", "ться", "ть", "ешь", "ет", "ут", "ют",
        "ит", "ат", "ят", "ал", "ала", "али", "ил", "ила", "или", "ого", "его", "ому",
        "ему", "ыми", "ими", "ых", "их", "а", "е", "и", "й", "о", "у", "ы", "ь", "я", "ю",
    },
    key=len,
    reverse=True,
)
_MIN_STEM = 3

# Служебные слова и команды ассистента, которые не несут смысла для поиска.
STOP_WORDS = frozenset(
    {
        "а", "в", "во", "на", "по", "о", "об", "обо", "про", "с", "со", "у", "к", "ко",
        "из", "за", "для", "до", "от", "и", "или", "но", "что", "где", "как", "когда",
        "там", "тут", "это", "эту", "этот", "та", "ту", "тот", "мне", "меня", "мой",
        "моя", "мою", "мои", "я", "ее", "её", "его", "их", "был", "была", "было", "были",
        "ставил", "ставила", "когда-то", "то", "ли", "же", "бы", "не", "все", "всё",
        "найди", "найти", "поищи", "поиск", "покажи", "показать", "напомни", "какая",
        "какие", "какой", "какую", "есть", "запись", "записи", "задачу", "задача",
        "задачи", "встречу", "встреча", "встречи", "напоминание", "напоминания",
    }
)

# Группы слов, близких по смыслу. Поиск расширяет запрос всеми словами группы.
SYNONYM_GROUPS: tuple[frozenset[str], ...] = (
    frozenset({"договор", "контракт", "соглашение", "документы", "бумаги"}),
    frozenset({"презентация", "слайды", "питч", "демо", "выступление", "доклад"}),
    frozenset({"встреча", "созвон", "митинг", "переговоры", "синк", "звонок"}),
    frozenset({"отчет", "доклад", "сводка", "отчетность"}),
    frozenset({"команда", "коллектив", "отдел", "коллеги"}),
    frozenset({"билеты", "авиабилеты", "поездка", "перелет", "самолет", "поезд"}),
    frozenset({"позвонить", "звонок", "набрать", "созвониться"}),
    frozenset({"дизайнер", "дизайн", "макеты", "фигма"}),
    frozenset({"врач", "доктор", "поликлиника", "клиника", "больница"}),
    frozenset({"купить", "покупка", "заказать", "магазин"}),
    frozenset({"оплатить", "оплата", "счет", "платеж"}),
    frozenset({"день рождения", "др", "праздник", "поздравить"}),
)


def fold(text: str) -> str:
    """Приводит текст к виду, в котором он лежит в индексе: нижний регистр, "ё" как "е"."""
    return text.lower().replace("ё", "е")


def words(text: str) -> list[str]:
    """Возвращает слова текста в нижнем регистре без пунктуации."""
    return _WORD_RE.findall(text.lower().replace("ё", "е"))


def stem(word: str) -> str:
    """Отрезает одно окончание, если после этого остается основа от трех букв."""
    word = word.lower().replace("ё", "е")
    for ending in _ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= _MIN_STEM:
            return word[: -len(ending)]
    return word


def keywords(text: str) -> list[str]:
    """Возвращает значимые слова запроса.

    Если запрос состоит только из служебных слов ("встреча"), функция
    возвращает их все, потому что иначе запрос стал бы пустым.
    """
    all_words = [w for w in words(text) if len(w) > 1 or w.isdigit()]
    meaningful = [w for w in all_words if w not in STOP_WORDS]
    return meaningful or all_words


def _build_synonym_index() -> dict[str, frozenset[str]]:
    index: dict[str, set[str]] = {}
    for group in SYNONYM_GROUPS:
        stems = {stem(w) for phrase in group for w in words(phrase)}
        for s in stems:
            index.setdefault(s, set()).update(stems)
    return {k: frozenset(v) for k, v in index.items()}


_SYNONYMS = _build_synonym_index()


def synonym_stems(word_stem: str) -> frozenset[str]:
    """Возвращает основы синонимов, включая саму основу.

    Сравнение идет по общему началу из четырех букв, чтобы "презентаци"
    совпала с "презентац", которую дает другой падеж.
    """
    result = {word_stem}
    for s, group in _SYNONYMS.items():
        if s == word_stem or (
            min(len(s), len(word_stem)) >= 4 and (s.startswith(word_stem) or word_stem.startswith(s))
        ):
            result.update(group)
    return frozenset(result)
